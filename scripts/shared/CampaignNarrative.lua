local Narrative = {}
function Narrative.Apply(catalog)
    for chapterIndex, beats in ipairs(chapters) do
        for stageIndex, beat in ipairs(beats) do
            local stage = catalog[chapterIndex].stages[stageIndex]
            stage.title = beat[1]
            stage.lines = {}
            for paragraph in beat[2]:gmatch("[^\n]+") do
                stage.lines[#stage.lines + 1] = paragraph
            end
            stage.dialogue = stage.dialogue or {}
            local conversation = exchanges[chapterIndex]
            stage.dialogue[#stage.dialogue + 1] = { speaker = "塔灵", text = conversation[stageIndex * 2 - 1] }
            stage.dialogue[#stage.dialogue + 1] = { speaker = "你", text = conversation[stageIndex * 2] }
        end
    end
end
return Narrative
